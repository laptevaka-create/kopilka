namespace Kopilka.Core.Domain;

/// <summary>
/// Результат удаления справочника (счёта или категории).
/// Удаление используемого справочника запрещено: историю транзакций
/// ломать нельзя, пользователь получает причину отказа, а не «просто нет».
/// </summary>
public enum DeleteResult
{
    /// <summary>Запись удалена.</summary>
    Deleted,

    /// <summary>Запись с таким идентификатором не найдена.</summary>
    NotFound,

    /// <summary>По записи есть транзакции — удаление запрещено.</summary>
    InUse,
}
